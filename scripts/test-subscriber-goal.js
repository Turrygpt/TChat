const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { EventEmitter } = require('node:events');
const { normalizeSubscriberGoal, advanceSubscriberGoals } = require('../src/subscriberGoal');
const { registerTwitchSubscriptions } = require('../src/twitchSubscriptions');
const goal = (id, platform = 'all', enabled = true) => ({ id, type: 'subscriber-goal', enabled, ...normalizeSubscriberGoal({ target: 2, platform }) });
const items = [goal('all'), goal('tw', 'twitch'), goal('hidden', 'all', false), goal('vk', 'vk')];
const events = [], published = [];
let saves = 0, broadcasts = 0;
const source = fs.readFileSync(require.resolve('../main.js'), 'utf8');
const context = vm.createContext({ advanceSubscriberGoals, streamWidgets: items, normalizeSubscriber: x => x, getSystemAlertRule: () => ({ enabled: false }), saveStreamWidgets: () => saves++, broadcastStreamWidgets: () => broadcasts++, socketServer: { emit: (name, payload) => events.push({ name, payload }) } });
vm.runInContext(source.slice(source.indexOf('function enqueueSubscriberAlert('), source.indexOf('function enqueueSubscriptionRenewalAlert(')), context);
const client = new EventEmitter();
registerTwitchSubscriptions(client, { publish: x => published.push(x), subscriberAlert: context.enqueueSubscriberAlert, renewalAlert: () => {} });
client.emit('subscription', '#channel', 'Alice', { plan: '1000' }, '', { id: '1' });
assert.deepEqual(items.map(w => w.current), [1, 1, 1, 0]);
assert.equal(saves, 1); assert.equal(broadcasts, 1); // independent of disabled alert rule
client.emit('subscription', '#channel', 'Alice', { plan: '1000' }, '', { id: '1' });
assert.equal(saves, 1); // deduplicate replay
client.emit('resub', '#channel', 'Alice', 3, '', { id: 'renewal' });
client.emit('submysterygift', '#channel', 'Donor', 10, {}, { id: 'batch' });
assert.equal(items[0].current, 1);
client.emit('subgift', '#channel', 'Donor', 1, 'Bob', {}, { id: '2' });
assert.equal(items[0].current, 2);
assert.equal(events.at(-1).payload[0].reached, true);
assert.equal(events.at(-1).payload[0].username, 'Bob');
context.enqueueSubscriberAlert({ id: 'test', platform: 'twitch', isTest: true });
assert.equal(items[0].current, 2);
const restored = items.map(w => ({ ...w, ...normalizeSubscriberGoal(JSON.parse(JSON.stringify(w))) }));
assert.equal(advanceSubscriberGoals(restored, { id: 'twitch:subscription:2', platform: 'twitch' }).length, 0);
const changes = advanceSubscriberGoals(restored, { id: 'vk-1', platform: 'vk' });
assert.equal(changes.length, 3); assert.equal(changes[0].reached, false);
assert.deepEqual(restored.map(w => w.current), [3, 2, 3, 1]);
assert.equal(normalizeSubscriberGoal({ target: NaN, current: Infinity }).target, 50);
assert.equal(normalizeSubscriberGoal({ target: -10, current: -5 }).current, 0);
assert.equal(normalizeSubscriberGoal({ sound: 'false' }).sound, false);
assert.equal(advanceSubscriberGoals(restored, { id: 'future', platform: 'youtube' }).length, 2);
assert.equal(normalizeSubscriberGoal({}).motivationIntervalSeconds, 300);
assert.equal(normalizeSubscriberGoal({ motivationIntervalSeconds: 1 }).motivationIntervalSeconds, 15);
assert.equal(normalizeSubscriberGoal({ motivationIntervalSeconds: 9000 }).motivationIntervalSeconds, 3600);
assert.equal(normalizeSubscriberGoal({ motivationEnabled: 'false' }).motivationEnabled, false);
console.log('Subscriber goal: counting, platform filters, gifts, duplicates, persistence, hidden widgets, alert independence and one-time completion passed.');
